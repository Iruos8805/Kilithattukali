"""Point the game's difficulty ladder at your trained checkpoints.

  uv run python tools/make_ladder.py --seed 1                 # writes configs/game/ladder.yaml
  uv run python tools/make_ladder.py --seed 2 --tag _eq --plus-prefix q
Levels: easy = scripted, medium = fine-tuned attack + imitation defence (about scripted-guard strength),
hard = league attack + league defence.
"""
import argparse
import os

import yaml


def entry(path):
    return {"path": path}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=1); ap.add_argument("--tag", default="_eq", help="league variant to use: '' or _eq")
    ap.add_argument("--prefix", default="p"); ap.add_argument("--out", default="configs/game/ladder.yaml")
    a = ap.parse_args()
    s, pre = a.seed, f"runs/{a.prefix}{a.seed}"
    ft, dd = f"{pre}_ft/attack/latest", f"{pre}_dagger_defence"
    la, ld = f"{pre}_lg2{a.tag}/attack/latest", f"{pre}_lg2{a.tag}/defence/latest"
    for pth in (ft, dd, la, ld):
        if not os.path.exists(os.path.join(pth, "metadata.json")):
            print(f"warning: {pth} not found (that level will fail to load)")
    old = yaml.safe_load(open(a.out)) if os.path.exists(a.out) else {}
    lad = {"hub_repo": old.get("hub_repo", "your-org/kilithattu-rl-checkpoints"), "levels": {
        "easy": old.get("levels", {}).get("easy") or {
            "main": {"attack": {"scripted": "scripted:crosser?aggression=0.7"}, "defence": {"scripted": "scripted:guard?reaction=0.15"}},
            "teammate": {"attack": {"scripted": "scripted:crosser?aggression=0.8"}, "defence": {"scripted": "scripted:guard?reaction=0.2"}}},
        "medium": {"main": {"attack": entry(ft), "defence": entry(dd)}, "teammate": {"attack": entry(ft), "defence": entry(dd)}},
        "hard": {"main": {"attack": entry(la), "defence": entry(ld)}, "teammate": {"attack": entry(ft), "defence": entry(ld)}},
    }}
    with open(a.out, "w") as f:
        f.write("# Generated by tools/make_ladder.py. easy = scripted; medium = fine-tuned attack + imitation defence;\n# hard = league attack + league defence.\n")
        yaml.safe_dump(lad, f, sort_keys=False)
    print("wrote", a.out)


if __name__ == "__main__":
    main()
